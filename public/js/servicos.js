/* ==========================================================
   Cor de destaque por área
   ========================================================== */

const cores = {
    apps:      { hex:"#A678FF", rgb:"166,120,255" }, // roxo (marca)
    sites:     { hex:"#3ED598", rgb:"62,213,152"  }, // verde
    design:    { hex:"#FF6FA6", rgb:"255,111,166" }, // rosa
    marketing: { hex:"#FFB648", rgb:"255,182,72"  }  // âmbar
};

function aplicarCor(nome){

    const cor = cores[nome];

    if(!cor) return;

    document.documentElement.style.setProperty("--acento", cor.hex);
    document.documentElement.style.setProperty("--acento-rgb", cor.rgb);

}

/* ==========================================================
   Animação de código (matrix) para a transição de "sites"
   ========================================================== */

let matrixInterval = null;

function iniciarMatrix(){

    const canvas = document.getElementById("matrix-canvas");

    if(!canvas || matrixInterval) return;

    const ctx = canvas.getContext("2d");

    canvas.width = canvas.offsetWidth;
    canvas.height = canvas.offsetHeight;

    const caracteres = "01ABCDEFGH{}<>/;=";
    const tamanho = 18;
    const colunas = Math.floor(canvas.width / tamanho);
    const gotas = Array(colunas).fill(1);

    matrixInterval = setInterval(()=>{

        ctx.fillStyle = "rgba(29,23,63,.15)";
        ctx.fillRect(0, 0, canvas.width, canvas.height);

        ctx.fillStyle = cores.sites.hex;
        ctx.font = tamanho + "px monospace";

        gotas.forEach((y, i)=>{

            const letra = caracteres[Math.floor(Math.random() * caracteres.length)];

            ctx.fillText(letra, i * tamanho, y * tamanho);

            if(y * tamanho > canvas.height && Math.random() > .96){
                gotas[i] = 0;
            }

            gotas[i]++;

        });

    }, 45);

}

function pararMatrix(){

    clearInterval(matrixInterval);
    matrixInterval = null;

}

/* ==========================================================
   Transição em tela cheia ao trocar de área
   ========================================================== */

function mostrarTransicao(nome){

    const overlay = document.getElementById("transicao");

    if(!overlay) return;

    aplicarCor(nome);

    document.querySelectorAll(".transicao-cena").forEach(cena=>{

        cena.classList.toggle("ativa", cena.dataset.cena === nome);

    });

    overlay.classList.add("ativa");

    if(nome === "sites"){
        iniciarMatrix();
    }

    setTimeout(()=>{

        overlay.classList.remove("ativa");
        pararMatrix();

    }, 1400);

}

