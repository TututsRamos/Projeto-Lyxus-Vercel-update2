/* ==========================================================
   Passo a passo em balões (com entrada ao rolar a página)
   ========================================================== */

function observarEtapas(){

    const balões = document.querySelectorAll(".etapa-balao");

    const observer = new IntersectionObserver((entradas)=>{

        entradas.forEach(entrada=>{

            if(entrada.isIntersecting){

                entrada.target.classList.add("visivel");
                observer.unobserve(entrada.target);

            }

        });

    }, { threshold:.3 });

    balões.forEach(b=> observer.observe(b));

}

function carregarTimeline(item){

    const timeline = document.getElementById("timeline");

    if(!timeline) return;

    timeline.innerHTML = "";

    item.etapas.forEach((etapa, i)=>{

        timeline.innerHTML += `
            <div class="etapa-balao" style="--delay:${(i * 0.25).toFixed(2)}s">
                <i class="ri-cursor-fill etapa-cursor"></i>
                <span class="etapa-numero">${i + 1}</span>
                <h4 class="etapa-titulo">${etapa.titulo}</h4>
                <p class="etapa-descricao">${etapa.descricao}</p>
            </div>
        `;

    });

    observarEtapas();

}

/* ==========================================================
   Feedbacks em carrossel

   Antes cada área (apps/sites/design/marketing) tinha sua
   própria lista de feedbacks, e a lista trocava toda vez que
   o visitante clicava em outra área. Agora os feedbacks de
   todas as áreas ficam reunidos num único carrossel (fixo,
   não muda mais com o seletor de área), e dá pra filtrar por
   área, por mais estrelas ou pelos depoimentos mais completos
   (texto mais longo/detalhado) — os filtros combinam entre si.
   ========================================================== */

const areaLabels = {
    apps:"Apps",
    sites:"Sites",
    design:"Design",
    marketing:"Marketing"
};

const todosFeedbacks = Object.entries(dados).flatMap(([area, item])=>
    item.feedbacks.map(f=> ({ ...f, area }))
);

let filtroFeedbackAtivo = "recentes";
let areaFeedbackAtiva = "todas";

function ordenarFeedbacks(lista, filtro){

    const copia = [...lista];

    if(filtro === "estrelas"){

        return copia.sort((a, b)=> (b.estrelas || 0) - (a.estrelas || 0));

    }

    if(filtro === "completos"){

        return copia.sort((a, b)=> b.texto.length - a.texto.length);

    }

    return copia;

}

function filtrarFeedbacksPorArea(lista, area){

    if(area === "todas") return lista;

    return lista.filter(f=> f.area === area);

}

function renderizarFeedbacks(filtro = filtroFeedbackAtivo, area = areaFeedbackAtiva){

    const feedback = document.getElementById("feedback-grid");

    if(!feedback) return;

    filtroFeedbackAtivo = filtro;
    areaFeedbackAtiva = area;

    document.querySelectorAll("[data-feedback-filtro]").forEach(botao=>{

        botao.classList.toggle("ativo", botao.dataset.feedbackFiltro === filtro);

    });

    document.querySelectorAll("[data-feedback-area]").forEach(botao=>{

        botao.classList.toggle("ativo", botao.dataset.feedbackArea === area);

    });

    feedback.innerHTML = "";

    const lista = ordenarFeedbacks(filtrarFeedbacksPorArea(todosFeedbacks, area), filtro);

    if(lista.length === 0){

        feedback.innerHTML = `<p class="feedback-vazio">Nenhum depoimento encontrado para esse filtro.</p>`;

    }

    lista.forEach(f=>{

        const estrelas = f.estrelas || 5;
        const cor = cores[f.area];

        feedback.innerHTML += `
            <div class="card">
                <div class="feedback-card-topo">
                    <span class="stars">${"★".repeat(estrelas)}${"☆".repeat(5 - estrelas)}</span>
                    ${cor ? `<span class="feedback-tag" style="--tag-cor:${cor.hex}">${areaLabels[f.area] || f.area}</span>` : ""}
                </div>
                <h3>${f.empresa}</h3>
                <p>${f.texto}</p>
            </div>
        `;

    });

    feedback.scrollTo({ left:0 });

    requestAnimationFrame(atualizarScrub);

}

function configurarFiltroFeedback(){

    document.querySelectorAll("[data-feedback-filtro]").forEach(botao=>{

        botao.addEventListener("click", ()=>{

            renderizarFeedbacks(botao.dataset.feedbackFiltro, areaFeedbackAtiva);

        });

    });

    document.querySelectorAll("[data-feedback-area]").forEach(botao=>{

        botao.addEventListener("click", ()=>{

            renderizarFeedbacks(filtroFeedbackAtivo, botao.dataset.feedbackArea);

        });

    });

}

function atualizarScrub(){

    const track = document.getElementById("feedback-grid");
    const fill = document.getElementById("feedback-scrub-fill");

    if(!track || !fill) return;

    const max = track.scrollWidth - track.clientWidth;
    const largura = max > 0 ? Math.min(100, (track.clientWidth / track.scrollWidth) * 100) : 100;
    const pos = max > 0 ? (track.scrollLeft / max) * (100 - largura) : 0;

    fill.style.width = largura + "%";
    fill.style.left = pos + "%";

}

function configurarCarrossel(){

    const track = document.getElementById("feedback-grid");
    const trilha = document.querySelector(".feedback-scrub");

    if(!track || !trilha) return;

    track.addEventListener("scroll", atualizarScrub);

    let arrastando = false;

    function irParaPosicao(clientX){

        const rect = trilha.getBoundingClientRect();
        let percentual = (clientX - rect.left) / rect.width;
        percentual = Math.max(0, Math.min(1, percentual));

        const max = track.scrollWidth - track.clientWidth;
        track.scrollLeft = max * percentual;

    }

    trilha.addEventListener("mousedown", e=>{
        arrastando = true;
        irParaPosicao(e.clientX);
    });

    window.addEventListener("mousemove", e=>{
        if(arrastando) irParaPosicao(e.clientX);
    });

    window.addEventListener("mouseup", ()=>{
        arrastando = false;
    });

    trilha.addEventListener("touchstart", e=>{
        irParaPosicao(e.touches[0].clientX);
    });

    trilha.addEventListener("touchmove", e=>{
        irParaPosicao(e.touches[0].clientX);
    });

}

/* ==========================================================
   FAQ em balões flutuantes (por área)
   ========================================================== */

function carregarFAQ(item){

    const grid = document.getElementById("faq-grid");

    if(!grid) return;

    grid.innerHTML = "";

    item.faq.forEach((f, i)=>{

        const bolha = document.createElement("div");

        bolha.className = "faq-bubble aberto";
        bolha.style.setProperty("--delay", (i * 0.3).toFixed(2) + "s");

        // leve bagunça: cada balão nasce com uma rotação e
        // deslocamento vertical sutis, sem desalinhar a coluna
        const rotacao = (Math.random() * 4 - 2).toFixed(2);
        const deslocaY = (Math.random() * 10 - 5).toFixed(1);

        bolha.style.setProperty("--rot", rotacao + "deg");
        bolha.style.setProperty("--desloca-y", deslocaY + "px");

        bolha.innerHTML = `
            <p class="faq-pergunta">${f.pergunta}</p>
            <p class="faq-resposta">${f.resposta}</p>
        `;

        bolha.addEventListener("click", ()=>{

            bolha.classList.toggle("aberto");

        });

        grid.appendChild(bolha);

    });

}

/* ==========================================================
   Carregar tudo para a área selecionada
   ========================================================== */

function carregar(nome){

    const item = dados[nome];

    if(!item) return;

    const titulo = document.getElementById("titulo-processo");
    const descricao = document.getElementById("descricao-processo");

    if(titulo) titulo.textContent = item.titulo;
    if(descricao) descricao.textContent = item.descricao;

    carregarTimeline(item);
    carregarFAQ(item);

    ativarSeletor(nome);

}

document.querySelectorAll("[data-servico]").forEach(el=>{

    el.addEventListener("click", ()=>{

        const nome = el.dataset.servico;

        mostrarTransicao(nome);
        carregar(nome);

        const processo = document.getElementById("processo");

        if(processo) processo.scrollIntoView({ behavior:"smooth", block:"start" });

    });

});

