/* ==========================================================
   Passo a passo em balões (com entrada ao rolar a página)
   ========================================================== */

function observarEtapas(){

    const balões = document.querySelectorAll(".etapa-balao");

    const observer = new IntersectionObserver((entradas)=>{

        entradas.forEach(entrada=>{

            if(entrada.isIntersecting){

                entrada.target.classList.add("visivel");
                observer.unobserve(entrada.target);

            }

        });

    }, { threshold:.3 });

    balões.forEach(b=> observer.observe(b));

}

